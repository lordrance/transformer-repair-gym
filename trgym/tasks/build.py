def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build_workspace(spec: TaskSpec, dest: Path, *, gold: bool = False) -> Path:
    """Create the workspace for `spec` at `dest`.

    With `gold=True` the mutation is skipped, producing the known-good solution.
    The verifier uses this to prove that a correct fix actually passes.
    """
    dest = Path(dest)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    target_src = (REFERENCE_DIR / spec.target_file).read_text(encoding="utf-8")
    mutated = target_src
    if not gold:
        for mutation in spec.mutations:
            mutated = mutation.apply(mutated)
        if mutated == target_src:
            raise ValueError(f"{spec.task_id}: mutation was a no-op")

    (dest / spec.target_file).write_text(mutated, encoding="utf-8")

    for name in spec.support_files:
        shutil.copy2(REFERENCE_DIR / name, dest / name)

    (dest / "SYMPTOM.md").write_text(
        SYMPTOM_TEMPLATE.format(
            task_id=spec.task_id, target_file=spec.target_file, symptom=spec.symptom
        ),
        encoding="utf-8",
    )
    (dest / "test_visible.py").write_text(
        VISIBLE_TEST_TEMPLATE.format(task_id=spec.task_id), encoding="utf-8"
    )
    (dest / "trgym_visible_checks.py").write_text(
        VISIBLE_RUNNER_TEMPLATE.format(
            visible=list(spec.visible_checks), task_id=spec.task_id
        ),
        encoding="utf-8",
    )
    return dest


def workspace_fingerprint(spec: TaskSpec, workspace: Path) -> dict[str, str]:
    """Hash the files the model is allowed to edit, for tamper detection."""
    out = {}
    for name in (spec.target_file, *spec.support_files):
        path = Path(workspace) / name
        out[name] = _sha256(path.read_text(encoding="utf-8")) if path.exists() else "MISSING"
    return out
